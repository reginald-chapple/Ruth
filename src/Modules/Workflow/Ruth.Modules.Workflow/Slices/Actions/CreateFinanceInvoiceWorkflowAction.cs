using System.Globalization;
using Ruth.Modules.Finance.Contracts.Invoices;
using Ruth.Modules.Workflow.Contracts.Actions;
using Ruth.SharedKernel.Messaging;
using Ruth.SharedKernel.Results;

namespace Ruth.Modules.Workflow.Slices.Actions;

internal sealed class CreateFinanceInvoiceWorkflowAction(ICommandDispatcher commandDispatcher)
    : IWorkflowAction
{
    public const string Key = "workflow.finance.create-invoice";

    public string ActionKey => Key;
    public string DisplayName => "Create Financial Invoice";
    public string Category => "Finance";
    public string Description =>
        "Issues an Invoice via Finance.Contracts (FinancialAccountId, Amount/AmountAttributeKey, Description) and records InvoiceId.";

    public async Task<Result<WorkflowActionDirective>> ExecuteAsync(
        WorkflowActionExecutionContext context,
        CancellationToken cancellationToken = default
    )
    {
        var cfg = context.Configuration;
        var accountId = ResolveGuid(cfg, context.WorkflowAttributes, "FinancialAccountId");
        var personId = ResolveGuid(cfg, context.WorkflowAttributes, "PersonId")
            ?? context.InitiatorPersonId;
        var amount = ResolveAmount(cfg, context.WorkflowAttributes);

        if (!accountId.HasValue || !personId.HasValue || amount <= 0m)
        {
            return Result.Failure<WorkflowActionDirective>(
                DomainError.Validation(
                    "Workflow.FinanceInvoiceInvalidConfig",
                    "FinancialAccountId, PersonId, and positive Amount are required."
                )
            );
        }

        var command = BuildCreateInvoiceCommand(context, accountId.Value, personId.Value, amount);
        var res = await commandDispatcher.SendAsync<CreateInvoiceCommand, InvoiceResponse>(
            command,
            cancellationToken
        );
        if (res.IsFailure)
        {
            return Result.Failure<WorkflowActionDirective>(res.PrimaryError);
        }

        var targetAttr =
            cfg.TryGetValue("TargetAttributeKey", out var tk) && !string.IsNullOrWhiteSpace(tk)
                ? tk.Trim()
                : "InvoiceId";
        var updates = new Dictionary<string, string?>(StringComparer.OrdinalIgnoreCase)
        {
            [targetAttr] = res.Value.Id.ToString("D"),
            ["InvoiceNumber"] = res.Value.InvoiceNumber,
        };

        return Result.Success(
            new WorkflowActionDirective(
                WorkflowActionOutcomeKind.Continue,
                $"Issued invoice {res.Value.InvoiceNumber}.",
                UpdatedWorkflowAttributes: updates
            )
        );
    }

    private static CreateInvoiceCommand BuildCreateInvoiceCommand(
        WorkflowActionExecutionContext context,
        Guid accountId,
        Guid personId,
        decimal amount
    )
    {
        var cfg = context.Configuration;
        _ = cfg.TryGetValue("Description", out var desc);
        _ = cfg.TryGetValue("CurrencyCode", out var currency);
        var issueDate = DateOnly.FromDateTime(context.NowUtc.UtcDateTime);
        var dueDays =
            cfg.TryGetValue("DueDays", out var rawDue)
            && int.TryParse(rawDue, CultureInfo.InvariantCulture, out var parsedDays)
            && parsedDays >= 0
                ? parsedDays
                : 14;

        return new CreateInvoiceCommand(
            personId,
            issueDate,
            issueDate.AddDays(dueDays),
            string.IsNullOrWhiteSpace(currency) ? "USD" : currency.Trim().ToUpperInvariant(),
            [
                new InvoiceLineItemSpec(
                    accountId,
                    string.IsNullOrWhiteSpace(desc) ? context.WorkflowName : desc.Trim(),
                    Quantity: 1m,
                    UnitAmount: amount
                ),
            ],
            IssueImmediately: true,
            Memo: $"Generated by workflow {context.WorkflowNumber}"
        );
    }

    private static Guid? ResolveGuid(
        IReadOnlyDictionary<string, string?> cfg,
        IReadOnlyDictionary<string, string?> attrs,
        string key
    )
    {
        return cfg.TryGetValue(key, out var raw) && Guid.TryParse(raw, out var g) ? g
            : attrs.TryGetValue(key, out var fromAttr) && Guid.TryParse(fromAttr, out var ga) ? ga
            : null;
    }

    private static decimal ResolveAmount(
        IReadOnlyDictionary<string, string?> cfg,
        IReadOnlyDictionary<string, string?> attrs
    )
    {
        return cfg.TryGetValue("AmountAttributeKey", out var attrKey)
            && !string.IsNullOrWhiteSpace(attrKey)
            && attrs.TryGetValue(attrKey.Trim(), out var attrVal)
            && decimal.TryParse(
                attrVal,
                NumberStyles.Number,
                CultureInfo.InvariantCulture,
                out var a1
            )
                ? a1
            : cfg.TryGetValue("Amount", out var literal)
            && decimal.TryParse(
                literal,
                NumberStyles.Number,
                CultureInfo.InvariantCulture,
                out var a2
            )
                ? a2
            : 0m;
    }
}
